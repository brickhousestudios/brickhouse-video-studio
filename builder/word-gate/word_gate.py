import argparse, json, os, re, sys
from collections import Counter
from pathlib import Path

TICKS = 254_016_000_000
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from paths import workdir  # noqa: E402

LDIR = str(workdir())
EXT = LDIR + "/ext-2026-11-03"

def norm(w):
    return w.upper().replace("’", "'").strip(".,!?")

def ecproj_words(path):
    d = json.load(open(path))
    comps = {}
    for iid, it in d["items"].items():
        k = it.get("kind", {})
        if not isinstance(k, dict) or "layers" not in k:
            continue
        words = {}
        for lay in k["layers"]:
            if (lay.get("source") or {}).get("type") == "Text":
                v = (lay.get("props", {}).get("children", [{}])[0]
                     .get("children", [{}])[0].get("value", {}) or {}).get("v", {})
                if isinstance(v, dict) and "text" in v:
                    words[lay["name"]] = norm(v["text"])
        if words:
            comps[it["name"]] = words
    return comps

ORDER = {
    "line1_and_i_stop_at_a_light_REDLIGHT_V2":
        ["AND", "I", "STOP", "AT", "A", "LIGHT"],
    "line1_and_i_stop_at_a_light_REDLIGHT_V3":
        ["AND", "I", "STOP", "AT", "A", "LIGHT"],
    "block2_she_pulled_down_the_window":
        ["SHE", "PULLED", "DOWN", "THE", "WINDOW"],
    "block2_hey": ["I", "SAID", "HEY"],
    "block3_line1_she_said_where_im_from":
        ["SHE", "SAID", "WHERE", "I'M", "FROM"],
    "block3_line2_i_told_her_im_not_around":
        ["I", "TOLD", "HER", "I'M", "NOT", "AROUND"],
    "block3_cue4_no_way":
        ["THEN_L0_1", "I_L0_1", "ASKED_L0_1", "WHERE_L0_1", "SHE_L0_1",
         "FROM_L0_1", "SHE_L1_2", "SAID_L1_1", "NO_L1_1", "WAY"],
}
EFFECT_DUP_LAYERS = {"REDLIGHT-bloom", "HEADER", "HEADER-RULE"}

def comp_stream(comp_words, comp_name):
    return [(comp_words[layer], layer) for layer in ORDER[comp_name]
            if layer in comp_words]

def ecproj_config_lines(path, comp_name):
    comps = ecproj_words(path)
    words = comps[comp_name]
    lines = {}
    for layer, w in words.items():
        if layer in EFFECT_DUP_LAYERS:
            continue
        m = re.search(r"_L(\d+)_", layer or "")
        if m:
            lines.setdefault(int(m.group(1)), []).append((layer, w))
    return lines

def config_lines(path):
    cfg = json.load(open(path))
    ops = cfg["ops"] if isinstance(cfg, dict) else cfg
    texts, land = {}, {}
    for o in ops:
        a = o.get("args", {})
        if a.get("command") == "layer.newText":
            p = a["params"]
            texts[p.get("name")] = norm(p.get("text") or p.get("content") or "")
        if o.get("tool") == "add_keyframe" and a.get("path") == "transform/opacity":
            for kf in a["keys"]:
                if kf["value"] == 100:
                    land[a["layer"]] = kf["time"]
                    break
    lines = {}
    for layer, w in texts.items():
        if layer == "HEADER":
            continue
        m = re.search(r"_L(\d+)_", layer or "")
        ln = int(m.group(1)) if m else -1
        lines.setdefault(ln, []).append((land.get(layer, 0.0), layer, w))
    return {ln: [(layer, w) for _, layer, w in sorted(rows)]
            for ln, rows in sorted(lines.items())}

def baseline_sections(path):
    secs, cur = {}, None
    for ln in open(path).read().splitlines():
        if ln.startswith("## "):
            cur = ln[3:].strip()
            secs[cur] = []
        elif ln.strip() and cur and not ln.startswith("#"):
            secs[cur].append([norm(w) for w in ln.split()])
    return secs

def words_of(lines):
    return [" ".join(w for _, w in rows) for rows in lines]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", default=f"{EXT}/gate/baseline.md")
    ap.add_argument("--projects", choices=["current", "v51"], default="current")
    args = ap.parse_args()
    base = baseline_sections(args.baseline)
    suf = "-v51" if args.projects == "v51" else ""
    failures = []

    def check(section, got_lines):
        want = base[section]
        ok = len(got_lines) == len(want) and all(
            Counter(g) == Counter(w) for g, w in zip(got_lines, want))
        print(f"[{section}] baseline {len(want)} lines vs current {len(got_lines)} -> "
              f"{'OK' if ok else 'DIFF'}")
        if not ok:
            for i, (g, w) in enumerate(zip(got_lines, want)):
                if Counter(g) != Counter(w):
                    print(f"  line {i}: baseline: {' '.join(w)}")
                    print(f"  line {i}: current : {' '.join(g)}")
                    print(f"    missing={list((Counter(w)-Counter(g)).elements())} "
                          f"extra={list((Counter(g)-Counter(w)).elements())}")
            if len(got_lines) != len(want):
                print(f"  line-count mismatch: {len(got_lines)} vs {len(want)}")
            failures.append(section)

    # B1 (always the original project — no v51 variant exists)
    b1 = ecproj_words(f"{LDIR}/108-lyric-type-line1-redlight-v2.ecproj")
    check("B1", [[w for w, _ in comp_stream(
        b1["line1_and_i_stop_at_a_light_REDLIGHT_V2"],
        "line1_and_i_stop_at_a_light_REDLIGHT_V2")]])
    # B2 / B3 (original or v51-audit projects)
    b2 = ecproj_words(f"{LDIR}/108-lyric-type-block2-v7{suf}.ecproj")
    check("B2", [[w for w, _ in comp_stream(b2["block2_she_pulled_down_the_window"],
                  "block2_she_pulled_down_the_window")]
                 + [w for w, _ in comp_stream(b2["block2_hey"], "block2_hey")]])
    b3 = ecproj_words(f"{LDIR}/108-lyric-type-block3-take2-v6{suf}.ecproj")
    l3 = [w for w, _ in comp_stream(b3["block3_line1_she_said_where_im_from"],
          "block3_line1_she_said_where_im_from")] + \
         [w for w, _ in comp_stream(b3["block3_line2_i_told_her_im_not_around"],
          "block3_line2_i_told_her_im_not_around")]
    l4 = [w for w, _ in comp_stream(b3["block3_cue4_no_way"], "block3_cue4_no_way")]
    check("B3", [l3, l4])
    # B4: current = build config; audit = v51 project lines
    if suf:
        m = ecproj_config_lines(f"{EXT}/108-lyric-type-block4-v51.ecproj",
                                "block4_cues5-8")
        check("B4", [[w for _, w in m[ln]] for ln in sorted(m)])
    else:
        m = config_lines(f"{EXT}/cfg-block4-build.json")
        check("B4", [[w for _, w in m[ln]] for ln in sorted(m)])
    # B5 / CH1 / CH2 from their build configs (unchanged by any swap)
    for sec, cfgf in (("B5", "cfg-block5-build.json"),
                      ("CH1", "cfg-chantA-build.json"),
                      ("CH2", "cfg-chantB-build.json")):
        m = config_lines(f"{EXT}/{cfgf}")
        check(sec, [[w for _, w in m[ln]] for ln in sorted(m)])
    # PV: current = v3 project; audit = v2 project (pre-correction span)
    pv_path = f"{EXT}/108-lyric-type-passageverse{'-v3' if not suf else '-v2'}.ecproj"
    m = ecproj_config_lines(pv_path, "passage_verse_89-111")
    check("PV", [[w for _, w in m[ln]] for ln in sorted(m)])
    # SPAN EXCLUSIVITY on the current PV (v3 only): lines landing <= 9.30
    if not suf:
        span_want = base["PV"][0] + base["PV"][1] + base["PV"][2]
        span_got = []
        for ln in (0, 3, 4):
            span_got += [w for _, w in m.get(ln, [])]
        cfg = json.load(open(f"{EXT}/cfg-pv-build-v3.json"))
        cops = cfg["ops"] if isinstance(cfg, dict) else cfg
        land = {}
        for o in cops:
            a = o.get("args", {})
            if o.get("tool") == "add_keyframe" and a.get("path") == "transform/opacity":
                for kf in a["keys"]:
                    if kf["value"] == 100:
                        land[a["layer"]] = kf["time"]
                        break
        first = {}
        for layer, t in land.items():
            mm = re.search(r"_L(\d+)_", layer or "")
            if mm:
                ln = int(mm.group(1))
                first[ln] = min(first.get(ln, 1e9), t)
        span_lines = sorted(ln for ln, t in first.items() if t <= 9.30)
        ok = span_lines == [0, 3, 4] and Counter(span_got) == Counter(span_want)
        print(f"[PV-SPAN] lines {span_lines}, words == BO's two lines: {ok}")
        if not ok:
            failures.append("PV-SPAN")

    print()
    if failures:
        print("GATE: FAIL — deviations from baseline in:", failures)
        return 1
    print("GATE: PASS — build matches the v5 baseline + BO's two passage fixes")
    return 0

if __name__ == "__main__":
    sys.exit(main())
